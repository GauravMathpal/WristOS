export interface AssistantAction {
  type: 'TASK' | 'MEMORY' | 'ALERT' | 'NONE'
  task?: { title: string; dueTime: string }
  memory?: { tag: string; fact: string }
  alert?: { message: string }
}

export interface ParsedReply {
  cleanText: string
  action: AssistantAction
}

/**
 * Checks if the text expresses an intention to create or record a task/deadline/to-do
 */
export function hasTaskIntent(text: string): boolean {
  const lower = text.toLowerCase().trim()
  return (
    /\b(have to|need to|must|have complete|complete|finish|submit|prepare|buy|call|schedule|remind|agenda|task|todo|to-do|due|deadline)\b/i.test(lower) ||
    /\b(tmr|tomorrow|tonight)\b/i.test(lower) ||
    /\b(by|at)\s+\d{1,2}(:\d{2})?\s*(am|pm)?\b/i.test(lower)
  )
}

/**
 * Checks if the text expresses an intention to save a memory or personal fact
 */
export function hasMemoryIntent(text: string): boolean {
  const lower = text.toLowerCase().trim()
  return /\b(remember that|remember|save fact that|save fact|note that|store fact|keep in mind|my \w+ is)\b/i.test(lower)
}

/**
 * Checks if the text expresses an intention to vibrate or send an alert to the watch
 */
export function hasAlertIntent(text: string): boolean {
  const lower = text.toLowerCase().trim()
  return /\b(vibrate|buzz|alert watch|ping watch|haptic|alarm)\b/i.test(lower)
}

/**
 * Extracts a clean task title and normalized due time from natural language text
 * e.g. "i have complete xyz task by tmr 5pm" -> { title: "Complete xyz task", dueTime: "Tomorrow, 5:00 PM" }
 */
export function extractTaskDetails(rawPrompt: string): { title: string; dueTime: string } {
  const text = rawPrompt.trim()
  const lower = text.toLowerCase()

  // 1. Detect Due Time
  let dueTime = 'Today'

  const isTmr = /\b(tmr|tomorrow)\b/i.test(lower)
  const isTonight = /\btonight\b/i.test(lower)
  const isToday = /\btoday\b/i.test(lower)

  const clockMatch = text.match(/\b(?:at|by\s+)?(\d{1,2})(?::(\d{2}))?\s*(am|pm)\b/i)
  let timeStr = ''
  if (clockMatch) {
    const hour = parseInt(clockMatch[1], 10)
    const min = clockMatch[2] ? clockMatch[2] : '00'
    const ampm = clockMatch[3].toUpperCase()
    timeStr = `${hour}:${min} ${ampm}`
  }

  if (isTmr) {
    dueTime = timeStr ? `Tomorrow, ${timeStr}` : 'Tomorrow'
  } else if (isTonight) {
    dueTime = timeStr ? `Tonight, ${timeStr}` : 'Tonight, 9:00 PM'
  } else if (isToday) {
    dueTime = timeStr ? `Today, ${timeStr}` : 'Today'
  } else if (timeStr) {
    dueTime = `Today, ${timeStr}`
  }

  // 2. Clean Title
  let title = text
    .replace(
      /^(please\s+)?(remind me to|create a task to|add a task to|add task to|add a task|add task|create task|schedule a task to|schedule to|schedule a task|schedule|i have to|i have|i need to|i must|i should|have to|need to|set a reminder to|set reminder to)\s*/i,
      ''
    )
    .replace(/\b(?:by|at|due|on)?\s*(?:tmr|tomorrow|tonight|today)(?:\s*(?:at|by)?\s*\d{1,2}(?::\d{2})?\s*(?:am|pm)?)?\b/gi, '')
    .replace(/\b(?:at|by)\s+\d{1,2}(?::\d{2})?\s*(?:am|pm)?\b/gi, '')
    .replace(/\b\d{1,2}(?::\d{2})?\s*(?:am|pm)\b/gi, '')
    .replace(/^[,\s.:;-]+|[,\s.:;-]+$/g, '')
    .trim()

  if (!title) title = text
  title = title.charAt(0).toUpperCase() + title.slice(1)

  return { title, dueTime }
}

/**
 * Extracts category and fact from natural language memory text
 */
export function extractMemoryDetails(rawPrompt: string): { tag: string; fact: string } {
  const text = rawPrompt.trim()
  const lower = text.toLowerCase()

  const fact = text
    .replace(/^(please\s+)?(remember that|remember|save fact that|save fact|note that|store fact|keep in mind)\s*/i, '')
    .replace(/^[,\s.:;-]+|[,\s.:;-]+$/g, '')
    .trim() || text

  let tag = 'Personal'
  if (lower.includes('health') || lower.includes('water') || lower.includes('bpm') || lower.includes('sleep') || lower.includes('blood') || lower.includes('cardio')) {
    tag = 'Health'
  } else if (lower.includes('watch') || lower.includes('pinetime') || lower.includes('ble') || lower.includes('hardware') || lower.includes('battery')) {
    tag = 'Hardware'
  } else if (lower.includes('study') || lower.includes('exam') || lower.includes('code') || lower.includes('assignment') || lower.includes('work') || lower.includes('project')) {
    tag = 'Work'
  } else if (lower.includes('car') || lower.includes('vehicle') || lower.includes('home') || lower.includes('wifi') || lower.includes('family')) {
    tag = 'Personal'
  }

  return { tag, fact }
}

/**
 * Parses raw text for [ACTION:TYPE|...] tags.
 * If userPrompt is provided and no tag was generated by the LLM, it automatically
 * extracts the action as a safety fallback.
 */
export function parseAssistantReply(rawText: string, userPrompt?: string): ParsedReply {
  const actionRegex = /\[ACTION:(TASK|MEMORY|ALERT)\|(.*?)\]/s
  const match = actionRegex.exec(rawText)

  if (match) {
    const cleanText = rawText.replace(match[0], '').trim()
    const type = match[1]
    const payload = match[2].split('|')

    if (type === 'TASK') {
      return {
        cleanText,
        action: {
          type: 'TASK',
          task: {
            title: payload[0]?.trim() || 'New Task',
            dueTime: payload[1]?.trim() || 'Today'
          }
        }
      }
    } else if (type === 'MEMORY') {
      return {
        cleanText,
        action: {
          type: 'MEMORY',
          memory: {
            tag: payload[0]?.trim() || 'General',
            fact: payload[1]?.trim() || ''
          }
        }
      }
    } else if (type === 'ALERT') {
      return {
        cleanText,
        action: {
          type: 'ALERT',
          alert: {
            message: payload[0]?.trim() || 'WristOS Alert'
          }
        }
      }
    }
  }

  // Fallback: If no explicit tag was returned by the LLM, inspect userPrompt for intent
  if (userPrompt) {
    if (hasTaskIntent(userPrompt)) {
      const { title, dueTime } = extractTaskDetails(userPrompt)
      let cleanText = rawText.trim()
      // If the LLM response didn't clearly state the task was scheduled, clarify it
      if (!cleanText || cleanText.includes("I don't have that") || cleanText.includes("I'm with you")) {
        cleanText = `I've added "${title}" to your agenda for ${dueTime}.`
      }
      return {
        cleanText,
        action: {
          type: 'TASK',
          task: { title, dueTime }
        }
      }
    }

    if (hasMemoryIntent(userPrompt)) {
      const { tag, fact } = extractMemoryDetails(userPrompt)
      let cleanText = rawText.trim()
      if (!cleanText || cleanText.includes("I don't have that") || cleanText.includes("I'm with you")) {
        cleanText = `Saved "${fact}" to your Knowledge Vault under #${tag}.`
      }
      return {
        cleanText,
        action: {
          type: 'MEMORY',
          memory: { tag, fact }
        }
      }
    }

    if (hasAlertIntent(userPrompt)) {
      let cleanText = rawText.trim()
      if (!cleanText || cleanText.includes("I don't have that") || cleanText.includes("I'm with you")) {
        cleanText = `Dispatched a haptic alert notification to your smartwatch.`
      }
      return {
        cleanText,
        action: {
          type: 'ALERT',
          alert: { message: 'WristOS Priority' }
        }
      }
    }
  }

  return {
    cleanText: rawText.trim(),
    action: { type: 'NONE' }
  }
}
